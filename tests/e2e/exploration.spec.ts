  await expect(page.locator('[data-action-id="inspect:sonnenwacht"]')).toBeVisible()
  await expect(page.locator('[data-action-id^="move:"]')).toHaveCount(0)

  await clickAction(page, /^Untersuche den Ort /)
  await expect(page.getByRole('heading', { name: 'Was möchtest du tun?' })).toBeVisible()
  await expect(page.locator('[data-action-id^="move:"]')).not.toHaveCount(0)

  await clickAction(page, /Gehe zum Alten Markt/)
  await expect(page.locator('.action-grid button')).toHaveCount(1)
  await expect(page.locator('[data-action-id="interaction:hebelstange_fund"]')).toHaveCount(0)

  await clickAction(page, /^Untersuche den Ort /)
  await expect(page.locator('[data-action-id="interaction:hebelstange_fund"]')).toBeVisible()
  await clickAction(page, /Gehe nach Sonnenwacht/)
  await expect(page.getByRole('button', { name: /^Untersuche den Ort erneut/ })).toBeVisible()
  await expect(page.locator('[data-action-id^="move:"]')).not.toHaveCount(0)
