test('weist einen unbekannten Import-Ort zurück und behält das laufende Abenteuer', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Wie heisst du?').fill('Mira')
  await clickAction(page, 'Abenteuer starten')
  await clickAction(page, /Gehe zum Alten Markt/)
  await expect(page.locator('.save-state')).toHaveText('Gespeichert')
  const save = await page.evaluate(async () => {
    const database = await new Promise<IDBDatabase>((resolve) => { const request = indexedDB.open('readingdungeon'); request.onsuccess = () => resolve(request.result) })
    const stored = await new Promise<{ value: Record<string, unknown> }>((resolve) => { const request = database.transaction('adventures').objectStore('adventures').get('current'); request.onsuccess = () => resolve(request.result) })
    database.close()
    return stored.value
  })
  await page.getByRole('link', { name: 'Einstellungen' }).click()
  await page.getByLabel('Spielstand importieren', { exact: true }).setInputFiles({ name: 'kaputt.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...save, currentAreaId: 'nirgendwo', visitedAreaIds: ['sonnenwacht', 'nirgendwo'] })) })
  await expect(page.getByRole('alert')).toContainText('unbekannter Eintrag')
  await expect(page.getByRole('button', { name: 'Import bestätigen' })).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.save-summary')).toContainText('Alter Markt')
  await expect(page.locator('.save-summary')).toContainText('Mira')
})
